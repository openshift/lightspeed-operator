#!/usr/bin/env bash
#
# OLS-3189: Sync agentic CRDs and RBAC from the lightspeed-agentic-operator repo
# at a pinned git ref into the lightspeed-operator bundle.
#
#   * CRDs stay in the mirrored upstream config/crd/bases/ directory
#   * RBAC (manager role/binding, run-approver role/binding, service account)
#     -> config/agentic/
#   * Every upstream config/ directory except samples/ -> config/agentic/<directory>/
#   * Bundle-safe webhook configurations and Service -> config/agentic/
#
# These are inputs to the unified bundle assembly (#2113). That assembly
# emits the CRDs as owned APIs and the agentic manager RBAC as CSV permissions
# on both OCP 4.x and 5.x; the Classic operator separately gates its console.
#
# The synced files must not be hand-edited; re-run this target to update them.
# CRD sync is file-based on purpose: the lightspeed-operator Go module does NOT
# import the agentic-operator API module.
#
# Usage:
#   AGENTIC_OPERATOR_REPO=<git url or path> AGENTIC_OPERATOR_REF=<fetch ref> \
#     AGENTIC_OPERATOR_COMMIT=<full sha> ./hack/sync_agentic_manifests.sh
set -euo pipefail

REPO="${AGENTIC_OPERATOR_REPO:?set AGENTIC_OPERATOR_REPO (git URL or local path)}"
REF="${AGENTIC_OPERATOR_REF:?set AGENTIC_OPERATOR_REF (branch, tag, or pull ref)}"
COMMIT="${AGENTIC_OPERATOR_COMMIT:?set AGENTIC_OPERATOR_COMMIT (full SHA-1)}"
if [[ ! "$COMMIT" =~ ^[0-9a-f]{40}$ ]]; then
  echo "error: AGENTIC_OPERATOR_COMMIT must be a full Git SHA-1" >&2
  exit 2
fi

REPO_ROOT="$(git rev-parse --show-toplevel)"
RBAC_DEST="${REPO_ROOT}/config/agentic"
SOURCE_DIRS_FILE="${RBAC_DEST}/.synced-config-dirs"
GEN_HEADER="# Generated by 'make sync-agentic-crds' from ${REPO} @ ${COMMIT}. DO NOT EDIT."

# Names the agentic RBAC uses in the bundle. The upstream manifests use the
# kustomize-time placeholder __OPERATOR_NAMESPACE__ and the service account name
# "controller-manager"; adapt them to the bundle's concrete names.
OPERATOR_NAMESPACE="openshift-lightspeed"
SA_UPSTREAM="controller-manager"
SA_BUNDLE="lightspeed-agentic-operator-controller-manager"

tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT

echo "Fetching ${REPO} @ ${REF} ..."
git init -q "${tmp}"
git -C "${tmp}" remote add origin "${REPO}"
git -C "${tmp}" fetch -q --depth 1 origin "${REF}"
actual=$(git -C "${tmp}" rev-parse FETCH_HEAD)
if [[ "$actual" != "$COMMIT" ]]; then
  echo "error: source ref moved: expected ${COMMIT}, fetched ${actual}; update the pin deliberately" >&2
  exit 1
fi
git -C "${tmp}" checkout -q FETCH_HEAD

# Validate the complete source before overwriting any checked-in input.
shopt -s nullglob
crds=("${tmp}"/config/crd/bases/agentic.openshift.io_*.yaml)
if [ "${#crds[@]}" -eq 0 ]; then
  echo "error: no agentic.openshift.io_*.yaml CRDs found at ${REF}" >&2
  exit 1
fi
for base in role role_binding run_approver_role run_approver_binding service_account; do
  if [ ! -f "${tmp}/config/rbac/${base}.yaml" ]; then
    echo "error: expected RBAC file missing at ${REF}: config/rbac/${base}.yaml" >&2
    exit 1
  fi
done
for dir in admission crd default manager rbac webhook; do
  if [ ! -d "${tmp}/config/${dir}" ]; then
    echo "error: expected config directory missing at ${REF}: config/${dir}" >&2
    exit 1
  fi
done
for base in manifests service networkpolicy; do
  if [ ! -f "${tmp}/config/webhook/${base}.yaml" ]; then
    echo "error: expected webhook file missing at ${REF}: config/webhook/${base}.yaml" >&2
    exit 1
  fi
done
mkdir -p "${RBAC_DEST}"

# Mirror each non-sample directory directly under config/agentic/. Track the
# directory names so a later pin can remove an entire directory deleted by
# upstream. The adapted crds/ and root-level bundle inputs are never removed.
source_dirs=()
for src in "${tmp}"/config/*; do
  [ -d "${src}" ] || continue
  dir="$(basename "${src}")"
  [ "${dir}" = "samples" ] && continue
  if [[ ! "${dir}" =~ ^[a-zA-Z0-9_-]+$ || "${dir}" = "crds" || "${dir}" = "upstream" ]]; then
    echo "error: unsafe or reserved upstream config directory: ${dir}" >&2
    exit 1
  fi
  source_dirs+=("${dir}")
done
old_dirs=()
if [ -f "${SOURCE_DIRS_FILE}" ]; then
  mapfile -t old_dirs < "${SOURCE_DIRS_FILE}"
fi
for dir in "${old_dirs[@]}"; do
  if [[ ! "${dir}" =~ ^[a-zA-Z0-9_-]+$ || "${dir}" = "crds" || "${dir}" = "samples" || "${dir}" = "upstream" ]]; then
    echo "error: unsafe or reserved synced config directory: ${dir}" >&2
    exit 1
  fi
done
# Refuse collisions with an unrelated directory before deleting any mirror.
for dir in "${source_dirs[@]}"; do
  if [ -e "${RBAC_DEST}/${dir}" ]; then
    case " ${old_dirs[*]} " in
      *" ${dir} "*) ;;
      *) echo "error: refusing to overwrite an unmanaged config directory: ${dir}" >&2; exit 1 ;;
    esac
  fi
done
for dir in "${old_dirs[@]}"; do
  rm -rf "${RBAC_DEST}/${dir}"
done
# Remove the previous nested mirror when upgrading to the flat layout.
rm -rf "${RBAC_DEST}/upstream"
: > "${SOURCE_DIRS_FILE}"
for dir in "${source_dirs[@]}"; do
  cp -R "${tmp}/config/${dir}" "${RBAC_DEST}/"
  echo "${dir}" >> "${SOURCE_DIRS_FILE}"
done
echo "  config/ (except samples/) -> config/agentic/<directory>/"

# CRDs are consumed directly from the mirrored upstream config/crd/bases/ tree.
# Do not create a second local CRD copy; advancing AGENTIC_OPERATOR_COMMIT
# should make incoming upstream CRD changes visible in exactly one place.

# --- RBAC: fixed set of files, namespace + service-account name adapted.
for base in role role_binding run_approver_role run_approver_binding service_account; do
  src="${tmp}/config/rbac/${base}.yaml"
  dest="${RBAC_DEST}/${base}.yaml"
  # The service account and its binding subject are the only places the SA name
  # appears; retarget just those to the bundle SA name.
  if [ "${base}" = "service_account" ] || [ "${base}" = "role_binding" ]; then
    sa_sed="s/name: ${SA_UPSTREAM}\$/name: ${SA_BUNDLE}/"
  else
    sa_sed=""
  fi
  {
    echo "${GEN_HEADER}"
    sed -e "1{/^---$/d}" -e "s/__OPERATOR_NAMESPACE__/${OPERATOR_NAMESPACE}/g" ${sa_sed:+-e "${sa_sed}"} "${src}"
  } > "${dest}"
  echo "  RBAC -> ${dest#"${REPO_ROOT}"/}"
done

# Webhook configurations live in the CSV and the Service is a standalone
# bundle manifest. The upstream NetworkPolicy remains in config/agentic/webhook/:
# operator-sdk cannot include it as a registry+v1 bundle manifest.
for base in manifests service; do
  src="${tmp}/config/webhook/${base}.yaml"
  dest="${RBAC_DEST}/${base}.yaml"
  {
    echo "${GEN_HEADER}"
    sed -e '1{/^---$/d}' \
      -e "s/__OPERATOR_NAMESPACE__/${OPERATOR_NAMESPACE}/g" \
      -e 's/control-plane: controller-manager$/control-plane: agentic-controller-manager/' \
      "${src}"
  } > "${dest}"
  echo "  Webhook -> ${dest#"${REPO_ROOT}"/}"
done

echo "Synced agentic config (except samples) from ${REPO} @ ${COMMIT}."
